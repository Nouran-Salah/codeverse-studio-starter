"""Export a `LessonArtifact` to formats people and tools can consume.

- `json`     full artifact (source of truth)
- `markdown` human-readable script for review and editing
- `srt`      subtitle track timed from the storyboard
- `manim`    a runnable Manim skeleton: one Scene per storyboard scene
"""

from __future__ import annotations

import json
import textwrap
from collections.abc import Callable
from typing import Literal

from codeverse.models.schemas import LessonArtifact

ExportFormat = Literal["json", "markdown", "srt", "manim"]
EXTENSIONS: dict[str, str] = {"json": "json", "markdown": "md", "srt": "srt", "manim": "py"}


def to_json(artifact: LessonArtifact) -> str:
    return json.dumps(artifact.model_dump(mode="json"), indent=2, ensure_ascii=False)


def to_markdown(artifact: LessonArtifact) -> str:
    plan, script, review = artifact.plan, artifact.script, artifact.review
    lines = [
        f"# {plan.title}",
        "",
        (
            f"**Audience:** {plan.audience.value} · **Status:** {artifact.status} · "
            f"**Review score:** {review.score}/100 · "
            f"**Runtime:** ~{artifact.storyboard.total_duration_seconds}s"
        ),
        "",
        "## Learning objectives",
        *[f"- {o}" for o in plan.learning_objectives],
    ]
    if plan.prerequisites:
        lines += ["", "## Prerequisites", *[f"- {p}" for p in plan.prerequisites]]
    lines += ["", "## Script", "", "### Introduction", "", script.introduction]
    for section in script.sections:
        lines += ["", f"### {section.heading}", "", section.narration]
        if section.key_terms:
            lines += ["", f"*Key terms:* {', '.join(section.key_terms)}"]
    lines += ["", "### Conclusion", "", script.conclusion, "", "## Storyboard", ""]
    lines += ["| # | Scene | Duration | Visual |", "|---|---|---|---|"]
    for scene in artifact.storyboard.scenes:
        visual = scene.visual_description.replace("|", "\\|")
        lines.append(
            f"| {scene.scene_number} | {scene.title} | "
            f"{scene.estimated_duration_seconds}s | {visual} |"
        )
    lines += ["", "## Review", "", review.summary]
    lines += [f"- **{i.severity.value}** `{i.code}`: {i.message}" for i in review.issues]
    return "\n".join(lines) + "\n"


def _narration_for(artifact: LessonArtifact, reference: str) -> str:
    script = artifact.script
    if reference == "introduction":
        return script.introduction
    if reference == "conclusion":
        return script.conclusion
    index = int(reference.removeprefix("sections[").removesuffix("]"))
    return script.sections[index].narration


def _srt_time(seconds: float) -> str:
    ms = round(seconds * 1000)
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02}:{m:02}:{s:02},{ms:03}"


def to_srt(artifact: LessonArtifact) -> str:
    blocks, start = [], 0.0
    for index, scene in enumerate(artifact.storyboard.scenes, start=1):
        end = start + scene.estimated_duration_seconds
        text = _narration_for(artifact, scene.narration_reference)
        blocks.append(f"{index}\n{_srt_time(start)} --> {_srt_time(end)}\n{text}\n")
        start = end
    return "\n".join(blocks)


def to_manim(artifact: LessonArtifact) -> str:
    """Generate a Manim Community script. Render with: manim -pql lesson.py Scene01"""
    out = [
        f'"""Manim skeleton for: {artifact.plan.title}',
        "",
        "Generated by Codeverse Studio. Each class is one storyboard scene; replace the",
        "placeholder animation with real visuals. Render: manim -pql <file> Scene01",
        '"""',
        "",
        "from manim import UP, FadeOut, Scene, Text, Write",
        "",
    ]
    for scene in artifact.storyboard.scenes:
        hold = max(1, scene.estimated_duration_seconds - 2)
        out += [
            "",
            f"class Scene{scene.scene_number:02}(Scene):",
            *textwrap.wrap(
                scene.visual_description, 88, initial_indent="    # ", subsequent_indent="    # "
            ),
            "    def construct(self):",
            f"        title = Text({scene.on_screen_text!r}, font_size=40).to_edge(UP)",
            "        self.play(Write(title), run_time=1)",
            f"        self.wait({hold})  # narration: {scene.narration_reference}",
            "        self.play(FadeOut(title), run_time=1)",
            "",
        ]
    return "\n".join(out) + "\n"


EXPORTERS: dict[str, Callable[[LessonArtifact], str]] = {
    "json": to_json,
    "markdown": to_markdown,
    "srt": to_srt,
    "manim": to_manim,
}


def export(artifact: LessonArtifact, fmt: ExportFormat) -> str:
    try:
        return EXPORTERS[fmt](artifact)
    except KeyError:
        raise ValueError(
            f"Unknown export format {fmt!r}; choose from {sorted(EXPORTERS)}"
        ) from None
